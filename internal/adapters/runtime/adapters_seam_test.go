// adapterTransaction is the transaction most adapter tests install: one family
// and one exact file.
func adapterTransaction() application.AdapterTransaction {
	return application.AdapterTransaction{
		Roots:      []string{"config/agents"},
		ExactPaths: []string{"AGENTS.md"},
		Files: []application.AdapterFile{
			{Path: "config/agents/a.md", Contents: "A"},
			{Path: "AGENTS.md", Contents: "root"},
		},
	}
}

func TestDiskAdapterStoreReplaceInstallsTheTransactionAndLeavesNoStage(t *testing.T) {
	m := repository(&callLog{}, map[string]string{"README.md": "r"})
	useDoubles(t, m, nil, nil)
	if err := (DiskAdapterStore{}).Replace("/repo", adapterTransaction()); err != nil {
		t.Fatalf("Replace = %v", err)
	}
	if got := string(m.get("/repo/config/agents/a.md").data); got != "A" {
		t.Fatalf("family file = %q, want A", got)
	}
	if got := string(m.get("/repo/AGENTS.md").data); got != "root" {
		t.Fatalf("exact file = %q, want root", got)
	}
	for name := range m.nodes {
		if strings.Contains(name, "rhino-adapter-transaction") {
			t.Fatalf("stage %s was left behind", name)
		}
	}
}

func TestDiskAdapterStoreReplaceReplacesPriorFamiliesAndFiles(t *testing.T) {
	m := repository(&callLog{}, map[string]string{
		"config/agents/old.md": "old",
		"AGENTS.md":            "prior",
	})
	useDoubles(t, m, nil, nil)
	if err := (DiskAdapterStore{}).Replace("/repo", adapterTransaction()); err != nil {
		t.Fatalf("Replace = %v", err)
	}
	if m.get("/repo/config/agents/old.md") != nil {
		t.Fatal("the prior family member survived the replacement")
	}
	if got := string(m.get("/repo/AGENTS.md").data); got != "root" {
		t.Fatalf("exact file = %q, want root", got)
	}
}

func TestDiskAdapterStoreReplaceRefusesEachUnsafeTransaction(t *testing.T) {
	cases := map[string]struct {
		root   string
		tx     application.AdapterTransaction
		before func(m *memFS)
	}{
		"root is a file":  {root: "/repo/README.md", tx: adapterTransaction()},
		"root is missing": {root: "/repo/absent", tx: adapterTransaction()},
		"invalid root": {root: "/repo", tx: application.AdapterTransaction{
			Roots: []string{"../x"}, Files: []application.AdapterFile{{Path: "../x/a", Contents: "a"}}}},
		"duplicate roots": {root: "/repo", tx: application.AdapterTransaction{
			Roots: []string{"a", "a"}, Files: []application.AdapterFile{{Path: "a/x", Contents: "x"}}}},
		"nested roots": {root: "/repo", tx: application.AdapterTransaction{
			Roots: []string{"a", "a/b"}, Files: []application.AdapterFile{{Path: "a/b/x", Contents: "x"}}}},
		"invalid exact path": {root: "/repo", tx: application.AdapterTransaction{
			ExactPaths: []string{""}}},
		"duplicate exact paths": {root: "/repo", tx: application.AdapterTransaction{
			ExactPaths: []string{"x", "x"}, Files: []application.AdapterFile{{Path: "x", Contents: "x"}}}},
		"exact path under a root": {root: "/repo", tx: application.AdapterTransaction{
			Roots: []string{"config"}, ExactPaths: []string{"config/x"},
			Files: []application.AdapterFile{{Path: "config/x", Contents: "x"}}}},
		"invalid generated path": {root: "/repo", tx: application.AdapterTransaction{
			Roots: []string{"a"}, Files: []application.AdapterFile{{Path: "../x", Contents: "x"}}}},
		"generated path outside every family": {root: "/repo", tx: application.AdapterTransaction{
			Roots: []string{"a"}, Files: []application.AdapterFile{{Path: "other/z", Contents: "z"}}}},
		"duplicate generated path": {root: "/repo", tx: application.AdapterTransaction{
			ExactPaths: []string{"AGENTS.md"},
			Files:      []application.AdapterFile{{Path: "AGENTS.md", Contents: "1"}, {Path: "AGENTS.md", Contents: "2"}}}},
		"exact path without bytes": {root: "/repo", tx: application.AdapterTransaction{
			ExactPaths: []string{"AGENTS.md"}}},
		"family crosses a link": {root: "/repo", tx: adapterTransaction(), before: func(m *memFS) {
			symlink(m, "config", "elsewhere")
		}},
		"family is a file": {root: "/repo", tx: adapterTransaction(), before: func(m *memFS) {
			m.nodes["/repo/config/agents"] = &memNode{perm: 0o644}
		}},
		"exact path is a directory": {root: "/repo", tx: adapterTransaction(), before: func(m *memFS) {
			m.nodes["/repo/AGENTS.md"] = &memNode{dir: true, perm: 0o755}
		}},
		"exact path is a link": {root: "/repo", tx: adapterTransaction(), before: func(m *memFS) {
			symlink(m, "AGENTS.md", "README.md")
		}},
		"family has no generated bytes": {root: "/repo", tx: application.AdapterTransaction{
			Roots: []string{"empty"}}},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			m := repository(&callLog{}, map[string]string{"README.md": "r", "elsewhere/keep": "k"})
			if tc.before != nil {
				tc.before(m)
			}
			useDoubles(t, m, nil, nil)
			if err := (DiskAdapterStore{}).Replace(tc.root, tc.tx); err == nil {
				t.Fatalf("Replace(%s) succeeded, want a refusal", name)
			}
		})
	}
}

func TestDiskAdapterStoreReplaceRollsBackEveryFailedFault(t *testing.T) {
	prior := func(log *callLog) *memFS {
		return repository(log, map[string]string{"config/agents/old.md": "old", "AGENTS.md": "prior"})
	}
	faultSweep(t, func(t *testing.T, log *callLog) func() error {
		useDoubles(t, prior(log), nil, nil)
		return func() error { return (DiskAdapterStore{}).Replace("/repo", adapterTransaction()) }
	}, "Stat")
}

func TestBoundedCaptureKeepsOnePastItsLimitAndCountsTheRest(t *testing.T) {
	capture := boundedCapture{limit: 4}
	if n, err := capture.Write([]byte("abcdefgh")); n != 8 || err != nil {
		t.Fatalf("Write = %d, %v; want 8, nil", n, err)
	}
	if string(capture.kept) != "abcde" || capture.total != 8 {
		t.Fatalf("kept %q total %d; want abcde and 8", capture.kept, capture.total)
	}
	if n, _ := capture.Write([]byte("zz")); n != 2 || string(capture.kept) != "abcde" || capture.total != 10 {
		t.Fatalf("a full capture kept %q total %d", capture.kept, capture.total)
	}
}

func TestFinishModelRefusesOversizedAndSignalledOutput(t *testing.T) {
	oversized := boundedCapture{limit: maxModelOutput, total: maxModelOutput + 1}
	if _, err := finishModel(&hostCommand{}, &oversized); err == nil || !strings.Contains(err.Error(), "too much output") {
		t.Fatalf("finishModel(oversized) = %v, want too much output", err)
	}
	signalled := boundedCapture{limit: 4}
	if _, err := finishModel(&hostCommand{}, &signalled); err == nil || !strings.Contains(err.Error(), "ended by signal") {
		t.Fatalf("finishModel(no state) = %v, want ended by signal", err)
	}
}

func TestDiskModelResolverRefusesInvalidVectors(t *testing.T) {
	for name, launch := range map[string]application.ModelLaunch{
		"no executable":  {},
		"blank program":  {Arguments: []string{"  "}},
		"option program": {Arguments: []string{"-model"}},
	} {
		if _, err := (DiskModelResolver{}).Resolve(launch); err == nil {
			t.Errorf("Resolve(%s) succeeded, want a refusal", name)
		}
	}
}
