func writeFile(t *testing.T, root, path, contents string) {
	t.Helper()
	full := filepath.Join(root, filepath.FromSlash(path))
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(contents), 0o644); err != nil {
		t.Fatal(err)
	}
}

func readFile(t *testing.T, root, path string) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(path)))
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func adapterTransaction() application.AdapterTransaction {
	return application.AdapterTransaction{
		Roots:      []string{"adapters/alpha"},
		ExactPaths: []string{"CLAUDE.md"},
		Files: []application.AdapterFile{
			{Path: "CLAUDE.md", Contents: "Read AGENTS.md.\n"},
			{Path: "adapters/alpha/reviewer.md", Contents: "route\n"},
			{Path: "adapters/alpha/catalog.json", Contents: "{}\n"},
		},
	}
}

func TestDiskAdapterStoreReplacesFamiliesAndExactFiles(t *testing.T) {
	root := t.TempDir()
	writeFile(t, root, "AGENTS.md", "Root.\n")
	writeFile(t, root, "CLAUDE.md", "stale\n")
	writeFile(t, root, "adapters/alpha/stale.md", "stale\n")
	writeFile(t, root, "adapters/alpha/nested/kept.md", "stale\n")
	writeFile(t, root, "other/kept.md", "untouched\n")
	if err := (runtime.DiskAdapterStore{}).Replace(root, adapterTransaction()); err != nil {
		t.Fatalf("replace = %v", err)
	}
	if got := readFile(t, root, "CLAUDE.md"); got != "Read AGENTS.md.\n" {
		t.Fatalf("CLAUDE.md = %q", got)
	}
	if got := readFile(t, root, "adapters/alpha/reviewer.md"); got != "route\n" {
		t.Fatalf("reviewer.md = %q", got)
	}
	if _, err := os.Stat(filepath.Join(root, "adapters", "alpha", "stale.md")); !os.IsNotExist(err) {
		t.Fatalf("stale family file survived: %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, "adapters", "alpha", "nested", "kept.md")); !os.IsNotExist(err) {
		t.Fatalf("stale nested family file survived: %v", err)
	}
	if got := readFile(t, root, "other/kept.md"); got != "untouched\n" {
		t.Fatalf("outside file changed: %q", got)
	}
	// A current tree replaces idempotently: nothing is left behind.
	if err := (runtime.DiskAdapterStore{}).Replace(root, adapterTransaction()); err != nil {
		t.Fatalf("second replace = %v", err)
	}
}

func TestDiskAdapterStoreRefusesOutsideItsNarrowBoundary(t *testing.T) {
	root := t.TempDir()
	writeFile(t, root, "AGENTS.md", "Root.\n")
	transaction := adapterTransaction()
	transaction.Files = append(transaction.Files,
		application.AdapterFile{Path: "elsewhere.md", Contents: "x\n"})
	if err := (runtime.DiskAdapterStore{}).Replace(root, transaction); err == nil ||
		!strings.Contains(err.Error(), "generated adapter path `elsewhere.md` is outside every declared adapter family or exact path") {
		t.Fatalf("outside-family write was not refused: %v", err)
	}
	missing := adapterTransaction()
	missing.Files = missing.Files[1:]
	if err := (runtime.DiskAdapterStore{}).Replace(root, missing); err == nil ||
		!strings.Contains(err.Error(), "every exact adapter path must have generated bytes") {
		t.Fatalf("missing exact file was not refused: %v", err)
	}
	nested := adapterTransaction()
	nested.Roots = []string{"adapters", "adapters/alpha"}
	if err := (runtime.DiskAdapterStore{}).Replace(root, nested); err == nil ||
		!strings.Contains(err.Error(), "adapter roots must be distinct, non-overlapping repository paths") {
		t.Fatalf("nested roots were not refused: %v", err)
	}
	if err := (runtime.DiskAdapterStore{}).Replace(filepath.Join(root, "missing"), adapterTransaction()); err == nil ||
		!strings.Contains(err.Error(), "cannot inspect adapter root") {
		t.Fatalf("missing root was not refused: %v", err)
	}
}

func TestDiskAdapterStoreRefusesLinksOnTheWayIn(t *testing.T) {
	root := t.TempDir()
	writeFile(t, root, "AGENTS.md", "Root.\n")
	writeFile(t, root, "real/reviewer.md", "route\n")
	if err := os.Symlink(filepath.Join(root, "real"), filepath.Join(root, "adapters")); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	transaction := application.AdapterTransaction{
		Roots: []string{"adapters"},
		Files: []application.AdapterFile{{Path: "adapters/reviewer.md", Contents: "route\n"}},
	}
	if err := (runtime.DiskAdapterStore{}).Replace(root, transaction); err == nil ||
		!strings.Contains(err.Error(), "adapter path `adapters` crosses a symbolic link") {
		t.Fatalf("linked family was not refused: %v", err)
	}
}

func TestDiskModelResolverRunsTheDeclaredVector(t *testing.T) {
	if _, err := os.Stat("/usr/bin/printf"); err != nil {
		t.Skip("printf unavailable")
	}
	output, err := (runtime.DiskModelResolver{}).Resolve(application.ModelLaunch{
		Arguments:      []string{"/usr/bin/printf", "model-1.9 model-1.10"},
		Directory:      t.TempDir(),
		TimeoutSeconds: 30,
	})
	if err != nil {
		t.Fatalf("resolve = %v", err)
	}
	if output != "model-1.9 model-1.10" {
		t.Fatalf("output = %q", output)
	}
}

func TestDiskModelResolverRefusesWithoutStartingAnythingUseful(t *testing.T) {
	rows := []struct {
		name      string
		arguments []string
		cause     string
	}{
		{"no executable", nil, "the model command declares no executable"},
		{"blank executable", []string{"  "}, "the model command's executable is invalid"},
		{"leading dash executable", []string{"-x"}, "the model command's executable is invalid"},
		{"missing program", []string{"/nonexistent-rhino-model-list"}, "could not start model command"},
		{"failing status", []string{"/bin/false"}, "the model command exited with status 1"},
	}
	for _, row := range rows {
		t.Run(row.name, func(t *testing.T) {
			_, err := (runtime.DiskModelResolver{}).Resolve(application.ModelLaunch{
				Arguments: row.arguments, Directory: t.TempDir(), TimeoutSeconds: 30,
			})
			if err == nil || !strings.Contains(err.Error(), row.cause) {
				t.Fatalf("error = %v, want it to contain %q", err, row.cause)
			}
		})
	}
}

func TestDiskModelResolverBoundsTimeAndText(t *testing.T) {
	if _, err := os.Stat("/bin/sleep"); err != nil {
		t.Skip("sleep unavailable")
	}
	_, err := (runtime.DiskModelResolver{}).Resolve(application.ModelLaunch{
		Arguments: []string{"/bin/sleep", "30"}, Directory: t.TempDir(), TimeoutSeconds: 1,
	})
	if err == nil || !strings.Contains(err.Error(), "the model command exceeded its timeout") {
		t.Fatalf("timeout error = %v", err)
	}
	_, err = (runtime.DiskModelResolver{}).Resolve(application.ModelLaunch{
		Arguments: []string{"/usr/bin/printf", "\\xff"}, Directory: t.TempDir(), TimeoutSeconds: 30,
	})
	if err == nil || !strings.Contains(err.Error(), "the model command emitted non-text output") {
		t.Fatalf("non-text error = %v", err)
	}
}
